use crate::meta::{BootInfo, Meta, with_root_subvol};

fn entry(out: &mut String, depth: usize, name: &str, boot: &BootInfo, subvol: &str, ro: bool) {
    let slashes = "/".repeat(depth);
    let pad = "    ".repeat(depth - 1);
    out.push_str(&format!("{slashes}{name}\n"));
    out.push_str(&format!("{pad}    protocol: linux\n"));
    out.push_str(&format!("{pad}    path: boot():/{}\n", boot.kernel));
    out.push_str(&format!(
        "{pad}    cmdline: {}\n",
        with_root_subvol(&boot.cmdline, subvol, ro)
    ));
    if !boot.initramfs.is_empty() {
        out.push_str(&format!("{pad}    module_path: boot():/{}\n", boot.initramfs));
    }
}

fn label(text: &str) -> String {
    let clean: String = text.chars().filter(|c| !c.is_control()).collect();
    clean.chars().take(60).collect()
}

/// Render `limine.conf`: the live entry first, then a Generations submenu
/// (newest first) in which every generation boots its own kernel and command
/// line, read-only, from its own snapshot.
pub fn render(live: &BootInfo, live_subvol: &str, gens: &[Meta]) -> String {
    let mut out = String::from(
        "# managed by forge: regenerated by `forge gen rewrite-limine`; do not edit\n\
         timeout: 5\n\n",
    );
    entry(&mut out, 1, "Novara", live, live_subvol, false);
    if !gens.is_empty() {
        out.push_str("\n/Generations\n");
        let mut sorted: Vec<&Meta> = gens.iter().collect();
        sorted.sort_by_key(|m| std::cmp::Reverse(m.id));
        for m in sorted {
            let name = format!("Generation {}: {}", m.id, label(&m.description));
            let subvol = format!("@snapshots/gen-{}", m.id);
            entry(&mut out, 2, &name, &m.boot(), &subvol, true);
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn boot(k: &str) -> BootInfo {
        BootInfo { kernel: format!("vmlinuz-{k}"), initramfs: format!("initramfs-{k}.img"), cmdline: "root=UUID=abc".into() }
    }

    fn meta(id: u32, k: &str, desc: &str) -> Meta {
        let b = boot(k);
        Meta { id, description: desc.into(), created: 0, kernel: b.kernel, initramfs: b.initramfs, cmdline: b.cmdline, store_paths: vec![] }
    }

    #[test]
    fn entries_without_an_initramfs_have_no_module_path() {
        let mut b = boot("6.3");
        b.initramfs.clear();
        assert!(b.validate().is_ok(), "an empty initramfs name means none");
        let mut m = meta(1, "6.1", "first");
        m.initramfs.clear();
        let c = render(&b, "@", &[m]);
        assert!(!c.contains("module_path"), "{c}");
        assert!(c.contains("path: boot():/vmlinuz-6.3"));
        assert!(c.contains("//Generation 1: first"));
    }

    #[test]
    fn live_entry_only_when_no_generations() {
        let c = render(&boot("6.2"), "@", &[]);
        assert!(c.contains("/Novara\n"));
        assert!(c.contains("cmdline: root=UUID=abc rootflags=subvol=@ rw"));
        assert!(!c.contains("Generations"));
    }

    #[test]
    fn each_generation_pins_its_own_kernel_and_subvolume() {
        let c = render(&boot("6.3"), "@", &[meta(1, "6.1", "first"), meta(2, "6.2", "second")]);
        assert!(c.contains("path: boot():/vmlinuz-6.3"), "live entry uses the current kernel");
        assert!(c.contains("//Generation 1: first"));
        assert!(c.contains("path: boot():/vmlinuz-6.1"));
        assert!(c.contains("rootflags=subvol=@snapshots/gen-1 ro"));
        assert!(c.contains("rootflags=subvol=@snapshots/gen-2 ro"));
        assert!(c.find("Generation 2").unwrap() < c.find("Generation 1").unwrap(), "newest first");
    }

    #[test]
    fn staged_rollback_boots_the_next_subvolume() {
        assert!(render(&boot("6.2"), "@.next", &[]).contains("rootflags=subvol=@.next rw"));
    }

    #[test]
    fn description_cannot_inject_entries() {
        let c = render(&boot("6.2"), "@", &[meta(1, "6.2", "x\n/Evil\n    cmdline: bad")]);
        assert!(!c.contains("\n/Evil"));
    }
}
